#[derive(Debug, Clone, PartialEq, Eq)]
pub struct EnvEntry {
    pub key: String,
    pub value: String,
}

pub fn is_valid_key(key: &str) -> bool {
    let mut chars = key.chars();
    match chars.next() {
        Some(c) if c.is_ascii_alphabetic() || c == '_' => {}
        _ => return false,
    }
    chars.all(|c| c.is_ascii_alphanumeric() || c == '_' || c == '.' || c == '-')
}

pub fn parse_dotenv(text: &str) -> (Vec<EnvEntry>, usize) {
    let mut entries = Vec::new();
    let mut skipped = 0;

    for raw_line in text.lines() {
        // Strip a UTF-8 BOM if present on the first line.
        let line = raw_line.trim().strip_prefix('\u{FEFF}').unwrap_or(raw_line.trim());
        if line.is_empty() || line.starts_with('#') {
            continue;
        }

        let line = line.strip_prefix("export ").unwrap_or(line).trim();
        if line.is_empty() || line.starts_with('#') {
            continue;
        }

        let eq_pos = match line.find('=') {
            Some(p) => p,
            None => {
                skipped += 1;
                continue;
            }
        };

        let key = line[..eq_pos].trim();
        if !is_valid_key(key) {
            skipped += 1;
            continue;
        }

        let mut value = line[eq_pos + 1..].trim().to_string();
        value = strip_inline_comment(&value);
        value = unquote(&value);

        entries.push(EnvEntry {
            key: key.to_string(),
            value,
        });
    }

    (entries, skipped)
}

fn strip_inline_comment(value: &str) -> String {
    let mut out = String::with_capacity(value.len());
    let mut chars = value.chars().peekable();
    let mut quote: Option<char> = None;

    while let Some(c) = chars.next() {
        if let Some(q) = quote {
            out.push(c);
            if c == q {
                quote = None;
            }
        } else if c == '"' || c == '\'' {
            quote = Some(c);
            out.push(c);
        } else if c == '#' && out.ends_with(' ') {
            out.pop();
            break;
        } else {
            out.push(c);
        }
    }

    out.trim_end().to_string()
}

fn unquote(value: &str) -> String {
    let bytes = value.as_bytes();
    if bytes.len() >= 2 {
        let first = bytes[0];
        let last = bytes[bytes.len() - 1];
        if (first == b'"' && last == b'"') || (first == b'\'' && last == b'\'') {
            let inner = &value[1..value.len() - 1];
            if first == b'"' {
                return unescape_double(inner);
            }
            return inner.to_string();
        }
    }
    value.to_string()
}

fn unescape_double(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    let mut chars = s.chars();
    while let Some(c) = chars.next() {
        if c == '\\' {
            match chars.next() {
                Some('n') => out.push('\n'),
                Some('t') => out.push('\t'),
                Some('r') => out.push('\r'),
                Some('"') => out.push('"'),
                Some('\\') => out.push('\\'),
                Some(other) => {
                    out.push('\\');
                    out.push(other);
                }
                None => out.push('\\'),
            }
        } else {
            out.push(c);
        }
    }
    out
}

fn escape_double(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    for c in s.chars() {
        match c {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            _ => out.push(c),
        }
    }
    out
}

fn needs_quotes(value: &str) -> bool {
    if value.is_empty() {
        return true;
    }
    if value != value.trim() {
        return true;
    }
    value.chars().any(|c| {
        c.is_whitespace() || matches!(c, '#' | '"' | '\'' | '`' | '$' | '\\' | '!' | '*')
    })
}

pub fn format_env(entries: &[EnvEntry]) -> String {
    let mut out = String::from("# Exported by apiman\n");
    for e in entries {
        if needs_quotes(&e.value) {
            out.push_str(&format!("{}=\"{}\"\n", e.key, escape_double(&e.value)));
        } else {
            out.push_str(&format!("{}={}\n", e.key, e.value));
        }
    }
    out
}

pub fn format_example(keys: &[String]) -> String {
    let mut out = String::from("# Generated by apiman export --format example (fill in values, no secrets included)\n");
    for k in keys {
        out.push_str(&format!("{k}=\n"));
    }
    out
}
